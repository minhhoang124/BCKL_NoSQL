import { describe, expect, it } from 'vitest';
import { ApiError } from '../../services/apiClient';
import { parseAdminSystemHealth } from './systemHealthApi';
import { readyHealth, unknownHealth } from './systemHealth.fixtures';
import canonicalSource from '../../../../BE/src/health/search-health-contract.ts?raw';
import generatedSource from './searchHealthContract.generated.ts?raw';

describe('Health canonical contract and contradictory envelopes', () => {
  it('keeps generated validation/projection identical to the checkout Backend', () => {
    const header = "// Generated by scripts/sync-search-health-ui-contract.mjs from the Backend's\n// pure canonical validator/projection. Do not edit; run the generator or --check.\n";
    expect(generatedSource.replace(/\r\n/g, '\n')).toBe(header + canonicalSource.replace(/\r\n/g, '\n').trimEnd() + '\n');
  });

  it.each([
    (value: Record<string, unknown>) => ({ ...value, servedAt: '2026-02-31T01:00:00.000Z' }),
    (value: Record<string, unknown>) => ({ ...value, search: { ...unknownHealth.search, errorCode: ['AI_TIMEOUT'] } }),
    (value: Record<string, unknown>) => ({ ...value, search: { ...unknownHealth.search, status: 'READY' } }),
    (value: Record<string, unknown>) => ({ ...value, search: { ...unknownHealth.search, errorCode: null } }),
    (value: Record<string, unknown>) => ({ ...value, search: { ...unknownHealth.search, snapshot: readyHealth.search.snapshot } }),
  ])('rejects malformed transport envelope %#', (mutate) => {
    expect(() => parseAdminSystemHealth(mutate(structuredClone(unknownHealth)))).toThrow(ApiError);
  });

  it.each([
    (snapshot: Record<string, unknown>) => ({ ...snapshot, generatedAt: '2099-01-01T00:00:00.000Z' }),
    (snapshot: Record<string, unknown>) => ({ ...snapshot, debug: true }),
    (snapshot: Record<string, unknown>) => ({ ...snapshot, capabilities: { ...readyHealth.search.snapshot.capabilities, hybridText: { status: 'UNKNOWN', reasonCodes: [] } } }),
  ])('rejects invalid producer observation %# before rendering it', (mutate) => {
    const response = structuredClone(readyHealth);
    expect(() => parseAdminSystemHealth({ ...response, search: { ...response.search, snapshot: mutate(response.search.snapshot) } })).toThrow(ApiError);
  });
});
