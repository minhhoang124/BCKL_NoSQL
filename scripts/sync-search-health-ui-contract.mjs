// Static, checkout-local generation. No network, schema download, dotenv or DB.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

if (process.argv.slice(2).some((arg) => arg !== '--check') || process.argv.length > 3)
  throw new Error('Usage: node scripts/sync-search-health-ui-contract.mjs [--check]');
const source = new URL('../BE/src/health/search-health-contract.ts', import.meta.url);
const target = new URL('../FE/src/features/admin-system-health/searchHealthContract.generated.ts', import.meta.url);
const header = "// Generated by scripts/sync-search-health-ui-contract.mjs from the Backend's\n// pure canonical validator/projection. Do not edit; run the generator or --check.\n";
const expected = header + readFileSync(source, 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected)
    throw new Error('Search health UI contract drift; regenerate from the current checkout.');
  console.log('Search health UI contract matches Backend source.');
} else {
  writeFileSync(target, expected, 'utf8');
  console.log(`Generated ${fileURLToPath(target)}`);
}
